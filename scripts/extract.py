"""把上游 kernel 源码抽取到 k3x/<op>/<impl>/，作为只读的研读副本。

    python scripts/extract.py                 # 按 k3x/manifest.py 抽取全部
    python scripts/extract.py kda_decode      # 只抽某个算子
    python scripts/extract.py --check         # 校验副本没有被手改、上游子模块没有变

规则：
  * 源码来自 third_party/ 里 pin 住的子模块，相对路径保持和上游一致，方便对照。
  * python 模式：从入口文件出发，沿 `root` 包内的 import 自动补齐依赖闭包；
    import 前缀 `root.` 改写成 `k3x.<op>.<impl>.root.`，不会和已安装的包冲突。
    除了 import 行，文件内容逐字不变。只为路径存在、但没有被直接 import 的包生成空 __init__.py。
  * cpp 模式：从入口文件出发，沿 #include 在 include_dirs 里补齐头文件闭包；文件逐字复制。
  * stubs：用最小替身替换某个上游模块（比如动态分发器），在 SOURCE.json 里记录原因。
  * 每个 impl 目录完全由本脚本管理，重新抽取会整个覆盖；研读笔记写在 k3x/<op>/README.md。
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
import re
import runpy
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "k3x"
GENERATED_INIT = "# Generated by scripts/extract.py: package marker only.\n"
INCLUDE_RE = re.compile(r'^\s*#\s*include\s*([<"])([^>"]+)[>"]', re.M)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def git_describe(repo: Path) -> dict:
    def run(*args: str) -> str:
        return subprocess.run(["git", "-C", str(repo), *args], capture_output=True,
                              text=True, check=True).stdout.strip()
    commit = run("rev-parse", "HEAD")
    tag = subprocess.run(["git", "-C", str(repo), "describe", "--tags", "--exact-match"],
                         capture_output=True, text=True).stdout.strip()
    url = run("config", "--get", "remote.origin.url")
    return {"url": url, "tag": tag or None, "commit": commit}


# ---------------------------------------------------------------- python 模式

def module_file(src: Path, dotted: str) -> Path | None:
    """dotted 模块名（相对 src_root）→ 上游文件；包返回 __init__.py。"""
    base = src.joinpath(*dotted.split("."))
    if base.with_suffix(".py").is_file():
        return base.with_suffix(".py")
    if (base / "__init__.py").is_file():
        return base / "__init__.py"
    return None


def package_of(src: Path, file: Path) -> str:
    # a/b/__init__.py 和 a/b/c.py 所在的包都是 a.b
    return ".".join(file.relative_to(src).parent.parts)


def python_imports(src: Path, file: Path, root: str) -> list[tuple[str, list[str]]]:
    """返回 (被 import 的模块, from-import 的名字) 列表，只保留 root 包内的。"""
    tree = ast.parse(file.read_text(), filename=str(file))
    pkg = package_of(src, file)
    found = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name == root or alias.name.startswith(root + "."):
                    found.append((alias.name, []))
        elif isinstance(node, ast.ImportFrom):
            if node.level:
                base = pkg.split(".")
                base = base[: len(base) - node.level + 1]
                mod = ".".join(base + ([node.module] if node.module else []))
            else:
                mod = node.module or ""
            if mod == root or mod.startswith(root + "."):
                found.append((mod, [a.name for a in node.names]))
    return found


def python_closure(src: Path, root: str, entries: list[Path], stubs: dict) -> set[Path]:
    """返回需要复制的上游文件；被 from-import 了非子模块名字的包会带上它的 __init__.py。"""
    stub_mods = {re.sub(r"\.__init__$", "", s[:-3].replace("/", ".")) for s in stubs}
    files: set[Path] = set()
    todo = list(entries)
    while todo:
        f = todo.pop()
        if f in files:
            continue
        files.add(f)
        for mod, names in python_imports(src, f, root):
            if mod in stub_mods:
                continue
            target = module_file(src, mod)
            if target is None:
                raise SystemExit(f"{f.relative_to(src)}: 找不到模块 {mod}")
            is_pkg = target.name == "__init__.py"
            if not is_pkg:
                todo.append(target)
                continue
            needs_init = not names  # `import a.b` 会执行 a/b/__init__.py
            for name in names:
                sub = module_file(src, f"{mod}.{name}")
                if sub is not None and f"{mod}.{name}" not in stub_mods:
                    todo.append(sub)
                elif sub is None:
                    needs_init = True
            if needs_init:
                todo.append(target)
    return files


def rewrite_imports(text: str, root: str, prefix: str) -> tuple[str, int]:
    pattern = re.compile(rf"^(\s*)(from|import)(\s+){re.escape(root)}(?=[.\s,]|$)", re.M)
    new, n = pattern.subn(lambda m: f"{m.group(1)}{m.group(2)}{m.group(3)}{prefix}", text)
    bare = re.search(rf"^\s*import\s+{re.escape(prefix)}[\w.]*\s*$", new, re.M)
    if bare:
        raise SystemExit(f"不支持 `import {root}.x` 形式（会改变绑定名），需要手工处理：{bare.group(0).strip()}")
    return new, n


def load_stub(stub: str) -> tuple[str, str]:
    """替身是 k3x/_stubs/ 下的文件；docstring 第一行就是使用它的原因。"""
    content = (OUT / "_stubs" / stub).read_text()
    doc = ast.get_docstring(ast.parse(content)) or ""
    return content, doc.splitlines()[0] if doc else stub


def extract_python(spec: dict, repo: Path, dest: Path, prefix: str, record: dict) -> None:
    src = repo / spec.get("src_root", ".")
    root = spec["root"]
    stubs = spec.get("stubs", {})
    files = python_closure(src, root, [repo / e for e in spec["entries"]], stubs)
    pkg_dirs = set()
    for f in sorted(files):
        rel = f.relative_to(src)
        raw = f.read_bytes()
        text, n = rewrite_imports(raw.decode(), root, f"{prefix}.{root}")
        out = dest / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)
        pkg_dirs.update(p for p in rel.parents if p != Path("."))
        record["files"].append({
            "path": str(rel), "upstream": str(f.relative_to(repo)),
            "upstream_sha256": sha256(raw), "sha256": sha256(text.encode()),
            "modified": f"import 前缀 {root} -> {prefix}.{root}（{n} 行）" if n else None,
        })
    for rel, stub in sorted(stubs.items()):
        content, reason = load_stub(stub)
        out = dest / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(content)
        pkg_dirs.update(p for p in Path(rel).parents if p != Path("."))
        record["stubs"].append({"path": rel, "stub": f"k3x/_stubs/{stub}", "reason": reason,
                                "sha256": sha256(content.encode())})
    for d in sorted(pkg_dirs):
        init = dest / d / "__init__.py"
        if not init.exists():
            init.write_text(GENERATED_INIT)
            record["generated"].append(str(d / "__init__.py"))
    unresolved = sorted({m for f in files for m in re.findall(rf"['\"]({re.escape(root)}\.[\w.]+)['\"]", f.read_text())})
    if unresolved:
        record["warnings"].append(f"源码里有字符串形式的 {root}.* 模块名（可能是动态 import），未改写：{unresolved}")


# ---------------------------------------------------------------- cpp 模式

def extract_cpp(spec: dict, repo: Path, dest: Path, record: dict) -> None:
    base = repo / spec["base"]
    inc_dirs = [repo / d for d in spec.get("include_dirs", [])]
    seen: set[Path] = set()
    external: set[str] = set()
    todo = [repo / e for e in spec["entries"]]
    while todo:
        f = todo.pop()
        if f in seen:
            continue
        seen.add(f)
        for kind, name in INCLUDE_RE.findall(f.read_text(errors="replace")):
            cands = ([f.parent / name] if kind == '"' else []) + [d / name for d in inc_dirs]
            hit = next((c.resolve() for c in cands if c.is_file()), None)
            if hit is not None and repo.resolve() in hit.parents:
                todo.append(hit)
            else:
                external.add(name)
    for f in sorted(seen | {repo / c for c in spec.get("copy", [])}):
        f = f.resolve()
        rel = f.relative_to(base.resolve())
        raw = f.read_bytes()
        out = dest / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(raw)
        record["files"].append({
            "path": str(rel), "upstream": str(f.relative_to(repo.resolve())),
            "upstream_sha256": sha256(raw), "sha256": sha256(raw), "modified": None,
        })
    record["external_includes"] = sorted(external)


# ---------------------------------------------------------------- 主流程

def extract(op: str, impl: str, spec: dict, submodules: dict) -> dict:
    repo = ROOT / submodules[spec["source"]]
    dest = OUT / op / impl
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    prefix = f"k3x.{op}.{impl}"
    record = {
        "op": op, "impl": impl, "lang": spec["lang"], "mode": spec["mode"],
        "description": spec.get("description", ""),
        "source": {"submodule": submodules[spec["source"]], **git_describe(repo)},
        "files": [], "stubs": [], "generated": [], "warnings": [],
        "notes": spec.get("notes", []),
    }
    if spec["mode"] == "python":
        record["import_prefix"] = f"{prefix}.{spec['root']}"
        extract_python(spec, repo, dest, prefix, record)
    else:
        extract_cpp(spec, repo, dest, record)
    # cpp 模式的目录不是 Python 包，不生成 __init__.py
    for d in (OUT, OUT / op) + ((dest,) if spec["mode"] == "python" else ()):
        init = d / "__init__.py"
        if not init.exists():
            init.write_text(GENERATED_INIT)
    (dest / "SOURCE.json").write_text(json.dumps(record, ensure_ascii=False, indent=2) + "\n")
    return record


def unresolved_imports(impl_dir: Path, prefix: str) -> list[str]:
    """python 模式副本里，所有以 prefix 开头的 import 都必须能在副本内找到对应文件。"""
    missing = []
    for f in sorted(impl_dir.rglob("*.py")):
        for node in ast.walk(ast.parse(f.read_text(), filename=str(f))):
            mods = []
            if isinstance(node, ast.Import):
                mods = [(a.name, []) for a in node.names]
            elif isinstance(node, ast.ImportFrom) and not node.level and node.module:
                mods = [(node.module, [a.name for a in node.names])]
            for mod, names in mods:
                if not mod.startswith(prefix):
                    continue
                target = module_file(ROOT, mod)
                if target is None:
                    missing.append(f"{f.relative_to(impl_dir)}: {mod}")
                elif target.name == "__init__.py" and target.read_text() == GENERATED_INIT:
                    absent = [n for n in names if module_file(ROOT, f"{mod}.{n}") is None]
                    missing += [f"{f.relative_to(impl_dir)}: {mod}.{n}" for n in absent]
    return missing


def check(op_filter: list[str]) -> int:
    bad = 0
    for meta in sorted(OUT.glob("*/*/SOURCE.json")):
        record = json.loads(meta.read_text())
        if op_filter and record["op"] not in op_filter:
            continue
        name = f"{record['op']}/{record['impl']}"
        repo = ROOT / record["source"]["submodule"]
        head = git_describe(repo)["commit"]
        if head != record["source"]["commit"]:
            print(f"[STALE] {name}: 子模块 {head[:7]} != 抽取时 {record['source']['commit'][:7]}")
            bad += 1
        for item in record["files"] + record["stubs"]:
            path = meta.parent / item["path"]
            if not path.is_file() or sha256(path.read_bytes()) != item["sha256"]:
                print(f"[EDITED] {name}/{item['path']}")
                bad += 1
        if record["mode"] == "python":
            for miss in unresolved_imports(meta.parent, record["import_prefix"]):
                print(f"[IMPORT] {name}: {miss}")
                bad += 1
    print("ok" if not bad else f"{bad} 处不一致")
    return 1 if bad else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("ops", nargs="*", help="只处理这些算子")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        return check(args.ops)
    manifest = runpy.run_path(str(OUT / "manifest.py"))
    for op, impls in manifest["OPS"].items():
        if args.ops and op not in args.ops:
            continue
        for impl, spec in impls.items():
            rec = extract(op, impl, spec, manifest["SUBMODULES"])
            print(f"{op}/{impl}: {len(rec['files'])} 个文件, {len(rec['stubs'])} 个替身, "
                  f"{len(rec['generated'])} 个生成的 __init__.py")
            for w in rec["warnings"]:
                print(f"  ! {w}")
            if rec.get("external_includes"):
                print(f"  外部头文件: {', '.join(rec['external_includes'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
